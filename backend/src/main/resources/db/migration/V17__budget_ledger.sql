CREATE TABLE budget_ledger_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 installation_id UUID NOT NULL REFERENCES shared_installations(id),
 owner_id UUID NOT NULL REFERENCES accounts(id),
 program_id VARCHAR(64) NOT NULL,
 facility_type VARCHAR(30) NOT NULL,
 event_type VARCHAR(16) NOT NULL CHECK(event_type IN ('ALLOCATE','RELEASE')),
 amount_krw NUMERIC(14,2) NOT NULL CHECK(amount_krw>0),
 effective_at TIMESTAMP WITH TIME ZONE NOT NULL,
 recorded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 provenance VARCHAR(24) NOT NULL CHECK(provenance IN ('LEGACY_IMPORT','LIVE_TRANSACTION')),
 accounting_version VARCHAR(64) NOT NULL,
 source_budget_policy TEXT,
 UNIQUE(installation_id,event_type)
);
CREATE INDEX budget_ledger_owner_cursor ON budget_ledger_entries(owner_id,id);
CREATE INDEX budget_ledger_owner_facility ON budget_ledger_entries(owner_id,facility_type);
